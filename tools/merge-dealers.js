/* Merges the dealer-gap bike data (src-data/data-dealers-next.js) into data.js,
   and applies the hand-checked number fixes that came with it.

     node tools/merge-dealers.js

   data.js itself is generated by a Python script that lives outside this repo,
   so this tool edits data.js in place and writes it back in the same format.
   It is idempotent: running it twice gives the same file.

   Rules:
   - No prices or part numbers are invented. New parts keep price:null,
     askPrice:true and every field exactly as the dealer file gives it.
   - A dealer number already in PARTS is merged onto that part (fits, note)
     instead of creating a second part with the same number.
   - No outbound links are kept: tools/catalogue-clean.js drops the dealer
     source_url / sources before writing (and translates / repairs names).
   - The dealer file's v / confirmed flags mean "v:1 + confirmed:verify = seen
     on a retailer page only". app.js treats confirmed:"verify" as unconfirmed.
   - Reference prices and dated stock remarks in dealer notes are research,
     not customer text: tools/dealer-notes.js strips them from every note this
     tool writes, including rows merged on an earlier run.
   - Parsun (marine) is not handled here: tools/build-equip.js reads it. */
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { cleanNote, cleanModelNote } = require("./dealer-notes");
const { clean } = require("./catalogue-clean");

const root = path.join(__dirname, "..");
const DATA = path.join(root, "data.js");
const src = fs.readFileSync(DATA, "utf8");
const names = [...src.matchAll(/^const (\w+) = /gm)].map(m => m[1]);
const head = src.slice(0, src.indexOf("const "));
const ctx = {};
vm.createContext(ctx);
vm.runInContext(src + `\n;globalThis.__D = {${names}};`, ctx);
vm.runInContext(fs.readFileSync(path.join(root, "src-data/data-dealers-next.js"), "utf8") +
  "\n;globalThis.__X = {DEALER_NEW_BRANDS, DEALER_MODELS, DEALER_PARTS};", ctx);
const D = ctx.__D;
const { DEALER_NEW_BRANDS, DEALER_MODELS, DEALER_PARTS } = ctx.__X;
for (const d of DEALER_PARTS) d.note = cleanNote(d.note);

const uniq = (a) => [...new Set(a.filter(Boolean))];
const addNote = (p, n) => {
  if (!n) return;
  const cur = (p.note || "").trim();
  if (cur.includes(n)) return;
  p.note = cur ? `${cur}; ${n}` : n;
};
const byId = (id) => D.PARTS.find(p => p.id === id);
const byOem = (oem) => D.PARTS.find(p => p.oem === oem);
const log = [];

/* ---------- Brands ---------- */
D.BRANDS = uniq([...D.BRANDS, ...DEALER_NEW_BRANDS]);

/* B8R is the Aerox Alpha family code; lets the superseding belt number decode. */
if (!D.FAMILY.B8R) D.FAMILY.B8R = "Yamaha Aerox Alpha 155";

/* ---------- Models ---------- */
/* Dealer names repeat the make ("CFMoto 150SC"); the site prints make + name,
   so the make is dropped from the name. */
const normName = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
for (const m of DEALER_MODELS) {
  if (D.MODELS.some(x => x.id === m.id)) continue;
  const name = m.name.startsWith(m.brand + " ") ? m.name.slice(m.brand.length + 1) : m.name;
  const clash = D.MODELS.find(x => x.brand === m.brand && normName(x.name) === normName(name));
  if (clash) throw new Error(`model name clash: ${m.id} vs ${clash.id}`);
  D.MODELS.push({ ...m, name });
  log.push(`model added: ${m.id}`);
}
for (const m of D.MODELS) {
  if (DEALER_MODELS.some(x => x.id === m.id)) m.note = cleanModelNote(m.note);
}

/* ---------- Parts ---------- */
/* Explicit merge targets that the plain number match would get wrong.
   d0094 (2DP-F5805-00 for Exciter 155) belongs on the Exciter front-pad row,
   where B63-F5805-00 is primary and 2DP-F5805-00 its alternate.
   d0083 (B8R-E7641-00 belt) supersedes the existing B65-E7641-00 belt row p016. */
const TARGET = { d0094: "p029", d0083: "p016" };
/* Tyres the dealer gives by size only: the size is the shop code, as for the
   existing tyre rows (OWN_SKU in app.js). */
const tyreSize = (p) => (p.cat === "tyre" && !p.oem && (p.name.match(/\d+\/\d+-\d+/) || [])[0]) || null;

function mergeInto(t, d) {
  t.merged_from = t.merged_from || [];
  if (t.merged_from.includes(d.id)) return;
  t.merged_from.push(d.id);
  t.fits = uniq([...t.fits, ...d.fits]);
  addNote(t, d.note);
  log.push(`merged ${d.id} (${d.oem}) into ${t.id}`);
}

for (const d of DEALER_PARTS) {
  if (byId(d.id) || D.PARTS.some(p => (p.merged_from || []).includes(d.id))) continue;
  const oem = d.oem || tyreSize(d);
  if (!oem) throw new Error("dealer part with no number: " + d.id);
  const target = TARGET[d.id] ? byId(TARGET[d.id]) : byOem(oem);
  if (target) { mergeInto(target, d); continue; }
  D.PARTS.push({ ...d, oem });
  log.push(`part added: ${d.id} ${oem}`);
}

/* ---------- Aerox / Exciter fixes ---------- */
/* a. Belt: B8R-E7641-00 supersedes B65-E7641-00. One row, both numbers searchable. */
const belt = byId("p016");
if (belt.oem === "B65-E7641-00") {
  belt.oem = "B8R-E7641-00";
  belt.alts = uniq(["B65-E7641-00", ...belt.alts]);
}
addNote(belt, "B65-E7641-00 superseded by B8R-E7641-00 (authorised Indonesian Yamaha dealer)");
belt.confirmed = "verify";

/* b. Rear pad 3C1-F5805-10 does not fit the Aerox 155 VVA: its rear is a drum. */
const rpad = byId("p028");
rpad.fits = rpad.fits.filter(f => f !== "aerox155");
if (!rpad.fits.length) rpad.confirmed = "verify";
addNote(rpad, "Not for Aerox 155 VVA: its rear brake is a drum (dealer data)");
const aerox = D.MODELS.find(m => m.id === "aerox155");
aerox.notice = "The Aerox 155 VVA has a drum rear brake, so it takes brake shoes, not a rear disc pad. " +
  "The rear shoe number is not confirmed yet: send your frame number and we will check it.";

/* c. Exciter front pad: B63-F5805-00 primary, 2DP-F5805-00 alternate. */
const fpad = byId("p029");
fpad.alts = uniq([...fpad.alts, "2DP-F5805-00"]);
fpad.fits = uniq([...fpad.fits, "yamaha-exciter155-vva-b5v"]);
addNote(fpad, "VERIFY: Webike lists 2DP-F5805-00 for Exciter T150/T155; B63-F5805-00 kept as primary");
fpad.confirmed = "verify";

/* ---------- Honda alternates (confirmed by the owner) ---------- */
function addAlt(id, oem, alt, note) {
  const p = byId(id);
  if (p.oem !== oem) throw new Error(`${id} is ${p.oem}, expected ${oem}`);
  p.alts = uniq([...p.alts, alt]);
  addNote(p, note);
}
addAlt("n0061", "06455-KVB-T01", "06455-KVB-912",
  "06455-KVB-912 = front pad for earlier Air Blade 110 (ANC110A 2008) / Click 110; ACA110B uses -T01. Check caliper.");
addAlt("n0211", "40530-KPH-902", "40530-KPH-901",
  "Honda lists -901 (DID420DX-104RB) and -902 (DID420AD-104RB) as Wave 125 drive chain variants; hondamoto.parts lists 880/900/901/902 as equivalent references.");

/* ---------- Dealer notes: no reference prices or stock remarks ---------- */
const dealerIds = new Set(DEALER_PARTS.map(d => d.id));
for (const p of D.PARTS) {
  if (dealerIds.has(p.id) || (p.merged_from || []).some(id => dealerIds.has(id))) p.note = cleanNote(p.note);
}

/* ---------- Integrity before writing ---------- */
const oems = D.PARTS.map(p => p.oem);
const dupOem = oems.filter((o, i) => oems.indexOf(o) !== i);
if (dupOem.length) throw new Error("duplicate part numbers: " + dupOem.join(", "));
const mids = new Set(D.MODELS.map(m => m.id));
const dangling = D.PARTS.flatMap(p => p.fits.filter(f => !mids.has(f)).map(f => p.id + "->" + f));
if (dangling.length) throw new Error("dangling fits: " + dangling.join(", "));

/* ---------- English names, repaired cut names, no outbound links ---------- */
clean(D);

/* ---------- Write back in the generator's format ---------- */
const out = head + names.map(n => `const ${n} = ${n === "BRANDS"
  ? "[" + D[n].map(s => JSON.stringify(s)).join(", ") + "]"
  : JSON.stringify(D[n], null, 1)};`).join("\n") + "\n";
fs.writeFileSync(DATA, out);
log.forEach(l => console.log("  " + l));
console.log(`data.js: ${D.MODELS.length} models, ${D.PARTS.length} parts, brands ${D.BRANDS.join(", ")}`);
